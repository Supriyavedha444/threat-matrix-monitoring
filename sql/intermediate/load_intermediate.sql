USE DATABASE NONPROD_FRAUD;
USE SCHEMA INTERMEDIATE;

INSERT INTO THREATMATRIX_EVENTS_INT
SELECT
    EVENT_ID,
    CUSTOMER_ID,
    CUSTOMER_NAME,
    EMAIL,
    COUNTRY,
    DEVICE,
    RISK_SCORE,

    CASE
        WHEN RISK_SCORE >= 70 THEN 'HIGH'
        WHEN RISK_SCORE >= 40 THEN 'MEDIUM'
        ELSE 'LOW'
    END AS RISK_LEVEL,

    STATUS,
    EVENT_TIME,
    LOAD_TS
FROM NONPROD_FRAUD.STAGE.THREATMATRIX_EVENTS_STAGE;